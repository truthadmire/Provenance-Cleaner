def _rendered_pdf_pixels(pdf: Path) -> tuple[bytes, bytes]:
    png = pdf.with_suffix(".png")
    subprocess.run([
        str(_ghostscript()), "-q", "-dSAFER", "-dBATCH", "-dNOPAUSE",
        "-sDEVICE=png16m", "-r72", f"-sOutputFile={png}", str(pdf),
    ], check=True, capture_output=True, timeout=30)
    data = png.read_bytes()
    offset, header, pixels = 8, b"", b""
    while offset < len(data):
        length = struct.unpack(">I", data[offset:offset + 4])[0]
        kind = data[offset + 4:offset + 8]
        payload = data[offset + 8:offset + 8 + length]
        if kind == b"IHDR":
            header = payload
        elif kind == b"IDAT":
            pixels += payload
        offset += 12 + length
    return header, zlib.decompress(pixels)


def _provenance_mp4() -> bytes:
    file_type = _isobmff_box(
        b"ftyp", b"isom" + struct.pack(">I", 0) + b"isomiso2mp41"
    )
    xmp = _isobmff_box(b"uuid", _XMP_UUID + b"Generated by AI toolchain")
    media = _isobmff_box(b"mdat", b"\x10\x20\x30\x40" * 8)
    return file_type + xmp + media


def _riff_chunk(chunk_id: bytes, payload: bytes) -> bytes:
    padding = b"\x00" if len(payload) & 1 else b""
    return chunk_id + struct.pack("<I", len(payload)) + payload + padding


def _provenance_wav() -> tuple[bytes, bytes]:
    samples = bytes(range(64)) * 4
    wave_format = _riff_chunk(
        b"fmt ", struct.pack("<HHIIHH", 1, 1, 8000, 8000, 1, 8)
    )
    software = _riff_chunk(b"ISFT", b"Generated by AI\x00")
    info = _riff_chunk(b"LIST", b"INFO" + software)
    data = _riff_chunk(b"data", samples)
    body = b"WAVE" + wave_format + info + data
    return b"RIFF" + struct.pack("<I", len(body)) + body, samples


