class HelperProcess:
    def __init__(self, helper_path: Path | None = None) -> None:
        self.stderr_text = ""
        environment = os.environ.copy()
        environment.update(
            {
                "PYTHONDONTWRITEBYTECODE": "1",
                "WATERMARKS_MAX_INPUT_BYTES": str(512 << 20),
                "WATERMARKS_SYNTHID_SCORER_URL": "http://127.0.0.1:9",
                "WATERMARKS_SYNTHID_SCORER_API_KEY": "must-not-be-used",
                "MARKLLM_DIR": "/must/not/be/used",
                "NOAI_WATERMARK_DIR": "/must/not/be/used",
                "MARKDIFFUSION_DIR": "/must/not/be/used",
                "REVERSE_SYNTHID_DIR": "/must/not/be/used",
                "C2PATOOL_SETTINGS": "/must/not/be/used.toml",
                "GS_OPTIONS": "-sDEVICE=must-not-be-used -dNOSAFER",
                "GS_LIB": "/must/not/be/used",
                "GS_FONTPATH": "/must/not/be/used",
            }
        )
        command = (
            [PACKAGED_HELPER]
            if PACKAGED_HELPER
            else [sys.executable, str(HELPER)]
        )
        if helper_path is not None:
            command = [sys.executable, str(helper_path)] if helper_path.suffix == ".py" else [str(helper_path)]
        self.process = subprocess.Popen(
            command,
            cwd=ROOT,
            env=environment,
            stdin=subprocess.PIPE,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            text=True,
            encoding="utf-8",
            bufsize=1,
        )

    def exchange(self, request: dict[str, Any] | str, timeout: float = 15.0) -> dict[str, Any]:
        assert self.process.stdin is not None
        assert self.process.stdout is not None
        line = request if isinstance(request, str) else json.dumps(request, separators=(",", ":"))
        self.process.stdin.write(line + "\n")
        self.process.stdin.flush()
        ready, _, _ = select.select([self.process.stdout], [], [], timeout)
        if not ready:
            self.close(force=True)
            self.fail_with_stderr("timed out waiting for helper response")
        response_line = self.process.stdout.readline()
        if not response_line:
            self.fail_with_stderr("helper exited without a response")
        response = json.loads(response_line)
        if not isinstance(response, dict):
            raise AssertionError(f"helper response is not an object: {response!r}")
        if set(response) - RESPONSE_FIELDS:
            raise AssertionError(f"unexpected response fields: {set(response) - RESPONSE_FIELDS}")
        return response

    def fail_with_stderr(self, message: str) -> None:
        if (
            self.process.poll() is not None
            and self.process.stderr is not None
            and not self.process.stderr.closed
        ):
            self.stderr_text += self.process.stderr.read()
        raise AssertionError(f"{message}; stderr={self.stderr_text!r}")

    def close(self, *, force: bool = False) -> None:
        if self.process.poll() is None:
            if force:
                self.process.terminate()
            elif self.process.stdin is not None:
                self.process.stdin.close()
            try:
                self.process.wait(timeout=5)
            except subprocess.TimeoutExpired:
                self.process.kill()
                self.process.wait(timeout=5)
        if self.process.stderr is not None and not self.process.stderr.closed:
            self.stderr_text += self.process.stderr.read()
            self.process.stderr.close()
        if self.process.stdout is not None and not self.process.stdout.closed:
            self.process.stdout.close()
        if self.process.stdin is not None and not self.process.stdin.closed:
            self.process.stdin.close()

    def __enter__(self) -> "HelperProcess":
        return self

    def __exit__(self, exc_type: object, exc: object, traceback: object) -> None:
        self.close(force=exc is not None)
        if exc is None and self.process.returncode != 0:
            self.fail_with_stderr(f"helper exited with {self.process.returncode}")


