def _png_chunk(chunk_type: bytes, payload: bytes) -> bytes:
    crc = zlib.crc32(chunk_type)
    crc = zlib.crc32(payload, crc) & 0xFFFFFFFF
    return (
        struct.pack(">I", len(payload))
        + chunk_type
        + payload
        + struct.pack(">I", crc)
    )


def _png_with_text(*entries: tuple[str, str]) -> bytes:
    signature = b"\x89PNG\r\n\x1a\n"
    header = struct.pack(">IIBBBBB", 1, 1, 8, 2, 0, 0, 0)
    pixels = zlib.compress(b"\x00\x00\x00")
    text_chunks = b"".join(
        _png_chunk(
            b"tEXt",
            key.encode("latin-1") + b"\x00" + value.encode("latin-1"),
        )
        for key, value in entries
    )
    return (
        signature
        + _png_chunk(b"IHDR", header)
        + text_chunks
        + _png_chunk(b"IDAT", pixels)
        + _png_chunk(b"IEND", b"")
    )


def _jpeg_segment(marker: int, payload: bytes) -> bytes:
    return b"\xff" + bytes([marker]) + struct.pack(">H", len(payload) + 2) + payload


def _jpeg_with_segments(*segments: tuple[int, bytes]) -> bytes:
    return _JPEG_1X1[:2] + b"".join(
        _jpeg_segment(marker, payload) for marker, payload in segments
    ) + _JPEG_1X1[2:]


def _zip_write(archive: zipfile.ZipFile, name: str, contents: str) -> None:
    entry = zipfile.ZipInfo(name, date_time=(2000, 1, 1, 0, 0, 0))
    entry.compress_type = zipfile.ZIP_DEFLATED
    entry.external_attr = 0o600 << 16
    archive.writestr(entry, contents.encode("utf-8"))


